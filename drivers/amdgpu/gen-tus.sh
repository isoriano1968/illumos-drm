# Writes tus.txt: the TUs of amdgpu.ko for the illumos configuration
# (gen-tus.mk), as paths relative to drivers/gpu/drm/amd/amdgpu, minus
# the TUs of EXCLUDED (each with its reason), plus the TTM, GPU scheduler
# and DRM helper TUs amdgpu needs (CARRIED, relative to the tree), which
# move to their own misc modules once they build.
#
#   drivers/amdgpu/gen-tus.sh <patched linux tree> > drivers/amdgpu/tus.txt
set -euo pipefail
PATH=/usr/gnu/bin:$PATH
export LC_ALL=C
HERE=$(cd "$(dirname "$0")" && pwd)
LINUX=${1:?usage: gen-tus.sh <linux tree>}
MAKE=${MAKE:-gmake}

# TU and reason
EXCLUDED="
amdgpu_vkms.c	GPL-2.0: MIT stub in illumos/amdgpu_vkms_stub.c
amdgpu_dma_buf.c	amdgpu's own dma_buf_ops: PRIME is the DRM core's, illumos/amdgpu_dma_buf_illumos.c
amdgpu_trace_points.c	tracepoints: lkpi has none (no-op trace headers)
/drivers/gpu/drm/ttm/ttm_bo_vm.c	Linux VM faults (vm_fault, vmf_insert_pfn): replaced by an illumos devmap path (to do)
/drivers/gpu/drm/ttm/ttm_backup.c	shmem swap-out of BOs: illumos/ttm_backup_illumos.c (none yet)

"
CARRIED="
drivers/gpu/drm/ttm/ttm_tt.c
drivers/gpu/drm/ttm/ttm_bo.c
drivers/gpu/drm/ttm/ttm_bo_util.c
drivers/gpu/drm/ttm/ttm_module.c
drivers/gpu/drm/ttm/ttm_execbuf_util.c
drivers/gpu/drm/ttm/ttm_range_manager.c
drivers/gpu/drm/ttm/ttm_resource.c
drivers/gpu/drm/ttm/ttm_pool.c
drivers/gpu/drm/ttm/ttm_device.c
drivers/gpu/drm/ttm/ttm_sys_manager.c
drivers/gpu/drm/scheduler/sched_main.c
drivers/gpu/drm/scheduler/sched_fence.c
drivers/gpu/drm/scheduler/sched_entity.c
drivers/gpu/drm/scheduler/sched_rq.c
drivers/gpu/drm/drm_exec.c
drivers/gpu/buddy.c
drivers/gpu/drm/drm_buddy.c
drivers/gpu/drm/drm_suballoc.c
"
echo "# Generated by drivers/amdgpu/gen-tus.sh from Linux $(git -C "$LINUX" describe --tags 2>/dev/null || echo '?'); do not edit."
echo "# amdgpu.ko's TUs (relative to drivers/gpu/drm/amd/amdgpu), then the"
echo "# carried TUs (relative to the tree, prefix '/'), then illumos/*.c."
echo "$EXCLUDED" | grep . | sed 's/^\([^\t]*\)\t\(.*\)/# excluded: \1 (\2)/'
"$MAKE" -s -f "$HERE/gen-tus.mk" LINUX="$LINUX" print | tr ' ' '\n' | grep . |
    sed 's/\.o$/.c/' | grep -vxF -f <(echo "$EXCLUDED" | grep . | cut -f1) |
    while read -r t; do
	# ../pm/x.c -> relative to amd/amdgpu; keep as is (build.sh resolves)
	[ -f "$LINUX/drivers/gpu/drm/amd/amdgpu/$t" ] ||
	    { echo "gen-tus.sh: $t not in the tree" >&2; exit 1; }
	echo "$t"
    done
echo "$CARRIED" | grep . | sed 's|^|/|'
echo "illumos/amdgpu_vkms_stub.c"
echo "illumos/amdgpu_dma_buf_illumos.c"
echo "illumos/amdgpu_illumos_kms.c"
echo "illumos/ttm_backup_illumos.c"
echo "illumos/amdgpu_illumos.c"
echo "illumos/amdgpu_illumos_mmap.c"
