# Generate opt-in alias data from the pinned Linux PCI IDs, not gfx-drm.
#
# Usage: gen-aliases.sh <patched Linux tree> > packaging/i915n.aliases
# The groups match patch 0009's PCH Gen6-Gen9.5 admission boundary. They must
# be reviewed together when that boundary changes. Requires a C preprocessor
# ($CC, default gcc).

set -eu
LC_ALL=C
export LC_ALL

die() {
	echo "$*" >&2
	exit 1
}

[ $# -eq 1 ] || die "usage: gen-aliases.sh <patched Linux tree>"
tree=$(cd "$1" && pwd -P)
here=$(cd "$(dirname "$0")" && pwd -P)
repo=$(cd "$here/../.." && pwd -P)
header=$tree/include/drm/intel/pciids.h
pci=$repo/linuxkpi/src/lkpi_pci.c
[ -r "$pci" ] || die "cannot read $pci"

# hexids: every 0x... number of the input as "VALUE HEX" (decimal value,
# lowercase hex without leading zeros), one per line, sorted by value.
hexids() {
	awk '
	function emit(h,    i, v, d) {
		h = tolower(h)
		sub(/^0+/, "", h)
		if (h == "")
			h = "0"
		v = 0
		for (i = 1; i <= length(h); i++) {
			d = index("0123456789abcdef", substr(h, i, 1)) - 1
			v = v * 16 + d
		}
		print v, h
	}
	{
		s = $0
		while (match(s, /0x[0-9a-fA-F]+/)) {
			emit(substr(s, RSTART + 2, RLENGTH - 2))
			s = substr(s, RSTART + RLENGTH)
		}
	}' | sort -n -u
}

# The preprocessor output is captured first so that a failing $CC stops
# the script (there is no pipefail in sh). $CC is split like a command line.
src=$(printf '#include "%s"\n#define ALIAS(id, ...) id\n' "$header"
for group in SNB IVB HSW BDW SKL KBL CFL WHL CML; do
	printf 'INTEL_%s_IDS(ALIAS)\n' "$group"
done)
set -f
cpp_out=$(printf '%s\n' "$src" | ${CC:-gcc} -E -P -x c -)
set +f
ids=$(printf '%s\n' "$cpp_out" | hexids)

# Cross-check the native stolen-memory inventory too. Patch 0009 excludes
# Valleyview (the only SoC in those four tables); every other listed ID
# must receive binding data. This catches separate groups such as WHL.
known=$(awk '
	!body && /static const uint16_t lkpi_intel_gen[6789][[][]] = [{]/ {
		body = 1
		$0 = substr($0, index($0, "{") + 1)
	}
	body {
		e = index($0, "};")
		if (e) {
			print substr($0, 1, e - 1)
			body = 0
		} else
			print
	}' "$pci" | hexids | awk '$2 !~ /^f3[0-3]$/')
[ "$ids" = "$known" ] ||
	die "alias groups and admitted stolen-memory inventory disagree"
[ -n "$ids" ] && printf '%s\n' "$ids" | awk '$2 == "1916" { f = 1 } END { exit !f }' ||
	die "Skylake 1916 missing from alias expansion"

echo "# SPDX-License-Identifier: MIT"
echo "# Generated by drivers/i915/gen-aliases.sh from drivers/i915/PIN."
echo "# PCH Gen6-Gen9.5 only; never install as IPS driver-action aliases."
echo "# drmadm select new binds these; legacy removes new-only bindings."
printf '%s\n' "$ids" | awk '{ print "pci8086," $2 }'
