"""Generates the parts of drm-uapi that bindgen cannot produce.

bindgen translates structures and plain `#define` constants, but it cannot
expand function-like macros, so the `DRM_IOCTL_*` numbers (which are
`DRM_IOWR(nr, struct x)` and friends) are generated here from the same
headers. The script also writes the two halves of the layout check:

* `tools/uapi/drm_layout.c`, compiled with gcc on illumos against the
  headers, prints the size of every structure and union, the offset of every
  named member and the value of every `DRM_IOCTL_*` macro;
* `xtask/src/uapi_table.rs` prints the same lines from the Rust definitions,
  so that `cargo xtask uapi-check` can compare the two mechanically.

Usage: gen_uapi.py <include/drm dir> <bindings.rs> <repo root>
"""

import re
import sys
from pathlib import Path

HEADERS = ["drm.h", "drm_mode.h", "virtgpu_drm.h"]

RUST_KEYWORDS = {
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for", "if", "impl",
    "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "self", "Self", "static",
    "struct", "super", "trait", "true", "type", "unsafe", "use", "where", "while", "async", "await", "dyn",
    "abstract", "become", "box", "do", "final", "macro", "override", "priv", "typeof", "unsized", "virtual",
    "yield", "try", "gen",
}

C_BASE_TYPES = {
    "unsigned int": "core::ffi::c_uint",
    "int": "core::ffi::c_int",
    "unsigned long": "core::ffi::c_ulong",
    "__u32": "__u32",
    "__u64": "__u64",
}

GENERATED_BY = (
    "Generated by tools/uapi/generate.sh (tools/uapi/gen_uapi.py) from the libdrm 2.4.109 headers\n"
    "with the illumos patch in tools/uapi/patches and virtgpu_drm.h of Linux v6.12\n"
    "(tools/uapi/include). Do not edit; rerun the generator."
)


def preprocess(text):
    """Removes comments and joins continued lines."""
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"//[^\n]*", " ", text)
    return text.replace("\\\n", " ")


def split_args(s):
    depth, cur, out = 0, "", []
    for ch in s:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def evaluate(expr, defines):
    """Evaluates the small integer expressions used as ioctl numbers."""
    total = 0
    for term in expr.split("+"):
        term = term.strip().strip("()").strip()
        if re.fullmatch(r"0[xX][0-9a-fA-F]+", term):
            total += int(term, 16)
        elif re.fullmatch(r"\d+", term):
            total += int(term)
        elif term in defines:
            total += evaluate(defines[term], defines)
        else:
            raise SystemExit(f"cannot evaluate ioctl number term {term!r} in {expr!r}")
    return total


def parse_headers(incdir):
    defines, ioctls, tagged = {}, [], set()
    for h in HEADERS:
        text = preprocess((incdir / h).read_text())
        for m in re.finditer(r"\b(struct|union)\s+(\w+)\s*\{", text):
            tagged.add((m.group(1), m.group(2)))
        for line in text.splitlines():
            m = re.match(r"\s*#\s*define\s+(\w+)\s+(.*?)\s*$", line)
            if not m:
                continue
            name, body = m.group(1), m.group(2)
            if not name.startswith("DRM_IOCTL_") or name == "DRM_IOCTL_BASE":
                defines[name] = body
                continue
            mm = re.fullmatch(r"(DRM_IO|DRM_IOR|DRM_IOW|DRM_IOWR)\s*\((.*)\)", body)
            if not mm:
                raise SystemExit(f"{h}: unexpected form for {name}: {body}")
            args = split_args(mm.group(2))
            ioctls.append((name, mm.group(1), args, h))
    names = [i[0] for i in ioctls]
    dups = {n for n in names if names.count(n) > 1}
    if dups:
        raise SystemExit(f"duplicate ioctl names: {sorted(dups)}")
    return defines, ioctls, tagged


def rust_type(ctype):
    ctype = " ".join(ctype.split())
    m = re.fullmatch(r"(struct|union)\s+(\w+)", ctype)
    if m:
        return m.group(2)
    if ctype in C_BASE_TYPES:
        return C_BASE_TYPES[ctype]
    raise SystemExit(f"unknown ioctl argument type {ctype!r}")


def parse_bindings(path):
    """Returns [(kind, name, [rust field names])] for every struct and union."""
    text = path.read_text()
    out = []
    for m in re.finditer(r"^pub (struct|union) (\w+) \{\n(.*?)^\}", text, flags=re.S | re.M):
        fields = re.findall(r"^\s+pub (\w+):", m.group(3), flags=re.M)
        out.append((m.group(1), m.group(2), fields))
    return out


def c_field(rust_name):
    if rust_name.endswith("_") and rust_name[:-1] in RUST_KEYWORDS:
        return rust_name[:-1]
    return rust_name


def is_anonymous(field):
    return field.startswith("__bindgen_anon") or field.startswith("_bitfield") or "__bindgen_padding" in field


def main():
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    incdir, bindings, root = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
    defines, ioctls, tagged = parse_headers(incdir)
    records = [r for r in parse_bindings(bindings) if (r[0], r[1]) in tagged]

    # crates/drm-uapi/src/ioctl.rs
    rs = ["// " + l for l in GENERATED_BY.splitlines()]
    rs += [
        "",
        "use crate::bindings::*;",
        "use crate::ioc::{drm_io, drm_ior, drm_iow, drm_iowr};",
        "",
    ]
    table = []
    for name, macro, args, header in ioctls:
        nr = evaluate(args[0], defines)
        if nr > 0xFF:
            raise SystemExit(f"{name}: number {nr:#x} does not fit in 8 bits")
        src = f"{macro}({', '.join(' '.join(a.split()) for a in args)})"
        rs.append(f"/// `{src}` from `{header}`.")
        if macro == "DRM_IO":
            rs.append(f"pub const {name}: u32 = drm_io({nr:#04x});")
        else:
            fn = {"DRM_IOR": "drm_ior", "DRM_IOW": "drm_iow", "DRM_IOWR": "drm_iowr"}[macro]
            rs.append(f"pub const {name}: u32 = {fn}::<{rust_type(args[1])}>({nr:#04x});")
        table.append(name)
    rs += ["", "/// Every `DRM_IOCTL_*` number above with its name, in header order.", "pub const DRM_IOCTLS: &[(&str, u32)] = &["]
    rs += [f'    ("{n}", {n}),' for n in table]
    rs += ["];", ""]
    (root / "usr/src/uts/common/io/drm/drm-uapi/src/ioctl.rs").write_text("\n".join(rs))

    # tools/uapi/drm_layout.c
    c = ["/* " + l + " */" for l in GENERATED_BY.splitlines()]
    c += [
        "/*",
        " * Prints the layout of every DRM uAPI structure and the value of every",
        " * DRM_IOCTL_* macro, one fact per line, for comparison with",
        " * `cargo xtask uapi-dump` by `cargo xtask uapi-check`. Build it on illumos",
        " * against the patched libdrm 2.4.109 headers:",
        " *   gcc -m64 -I<include/drm> -o drm_layout drm_layout.c",
        " */",
        "#include <stdio.h>",
        "#include <stddef.h>",
        '#include "drm.h"',
        '#include "drm_mode.h"',
        '#include "virtgpu_drm.h"',
        "",
        "int",
        "main(void)",
        "{",
    ]
    for kind, name, fields in records:
        c.append(f'\t(void) printf("size {name} %zu\\n", sizeof ({kind} {name}));')
        if kind == "struct":
            for f in fields:
                if is_anonymous(f):
                    continue
                c.append(f'\t(void) printf("off {name} {f} %zu\\n", offsetof({kind} {name}, {c_field(f)}));')
    for name in table:
        c.append(f'\t(void) printf("ioctl {name} 0x%08x\\n", (unsigned int){name});')
    c += ["\treturn (0);", "}", ""]
    (root / "usr/src/tools/uapi/drm_layout.c").write_text("\n".join(c))

    # xtask/src/uapi_table.rs
    x = ["// " + l for l in GENERATED_BY.splitlines()]
    x += [
        "",
        "//! The Rust half of the uAPI layout check; see `tools/uapi/drm_layout.c`.",
        "",
        "use core::mem::{offset_of, size_of};",
        "",
        "use drm_uapi::*;",
        "",
        "/// Returns one line per fact, in the same format and order as `drm_layout.c`.",
        "pub fn lines() -> Vec<String> {",
        "    let mut v = Vec::new();",
    ]
    for kind, name, fields in records:
        x.append(f'    v.push(format!("size {name} {{}}", size_of::<{name}>()));')
        if kind == "struct":
            for f in fields:
                if is_anonymous(f):
                    continue
                x.append(f'    v.push(format!("off {name} {f} {{}}", offset_of!({name}, {f})));')
    x += [
        "    for (name, value) in DRM_IOCTLS {",
        '        v.push(format!("ioctl {name} 0x{value:08x}"));',
        "    }",
        "    v",
        "}",
        "",
    ]
    (root / "usr/src/tools/xtask/src/uapi_table.rs").write_text("\n".join(x))
    print(f"{len(records)} structures and unions, {len(table)} ioctls")


if __name__ == "__main__":
    main()
