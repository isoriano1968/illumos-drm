"""Writes crates/drm-uapi/src/abi.rs: compile-time checks of the structures
the DRM core and the planned drivers depend on, with the values gcc printed
on illumos (tools/uapi/drm_layout.oibldofgate.out, produced by
tools/uapi/drm_layout.c and tools/uapi/virtgpu_compat_layout.c).

bindgen already emits layout assertions for every structure, computed by
clang for x86_64-pc-solaris2.11. These add the values from the C compiler
that builds illumos userland, for the structures named in the R0 work item,
and pin the command numbers the core dispatches on.

Usage: gen_abi.py <gcc output> <repo root>
"""

import re
import sys
from pathlib import Path

STRUCTS = [
    # R0 core ioctls
    "drm_version", "drm_unique", "drm_auth", "drm_client", "drm_set_version",
    "drm_get_cap", "drm_set_client_cap",
    # GEM and PRIME (R1, R2)
    "drm_gem_close", "drm_gem_flink", "drm_gem_open", "drm_prime_handle",
    # syncobj (R2)
    "drm_syncobj_create", "drm_syncobj_destroy", "drm_syncobj_handle", "drm_syncobj_transfer",
    "drm_syncobj_wait", "drm_syncobj_timeline_wait", "drm_syncobj_array", "drm_syncobj_timeline_array",
    # KMS and atomic (R3)
    "drm_mode_modeinfo", "drm_mode_card_res", "drm_mode_crtc", "drm_mode_get_encoder",
    "drm_mode_get_connector", "drm_mode_get_property", "drm_mode_property_enum", "drm_mode_get_blob",
    "drm_mode_create_blob", "drm_mode_destroy_blob", "drm_mode_obj_get_properties",
    "drm_mode_obj_set_property", "drm_mode_get_plane_res", "drm_mode_get_plane", "drm_mode_set_plane",
    "drm_mode_fb_cmd2", "drm_mode_crtc_page_flip_target", "drm_mode_create_dumb", "drm_mode_map_dumb",
    "drm_mode_destroy_dumb", "drm_mode_atomic",
]
STRUCT_PREFIXES = ["drm_virtgpu_"]
IOCTLS = [
    "DRM_IOCTL_VERSION", "DRM_IOCTL_GET_UNIQUE", "DRM_IOCTL_GET_MAGIC", "DRM_IOCTL_GET_CLIENT",
    "DRM_IOCTL_SET_VERSION", "DRM_IOCTL_GET_CAP", "DRM_IOCTL_SET_CLIENT_CAP", "DRM_IOCTL_SET_UNIQUE",
    "DRM_IOCTL_AUTH_MAGIC", "DRM_IOCTL_SET_MASTER", "DRM_IOCTL_DROP_MASTER",
    # virtio-gpu (R4), with the older layouts of virtgpu_compat.rs
    "DRM_IOCTL_VIRTGPU_MAP", "DRM_IOCTL_VIRTGPU_EXECBUFFER", "DRM_IOCTL_VIRTGPU_EXECBUFFER_V1",
    "DRM_IOCTL_VIRTGPU_EXECBUFFER_V2", "DRM_IOCTL_VIRTGPU_GETPARAM", "DRM_IOCTL_VIRTGPU_RESOURCE_CREATE",
    "DRM_IOCTL_VIRTGPU_RESOURCE_INFO", "DRM_IOCTL_VIRTGPU_TRANSFER_FROM_HOST",
    "DRM_IOCTL_VIRTGPU_TRANSFER_FROM_HOST_V1", "DRM_IOCTL_VIRTGPU_TRANSFER_TO_HOST",
    "DRM_IOCTL_VIRTGPU_TRANSFER_TO_HOST_V1", "DRM_IOCTL_VIRTGPU_WAIT", "DRM_IOCTL_VIRTGPU_GET_CAPS",
    "DRM_IOCTL_VIRTGPU_RESOURCE_CREATE_BLOB", "DRM_IOCTL_VIRTGPU_CONTEXT_INIT",
]


def main():
    out_file, root = Path(sys.argv[1]), Path(sys.argv[2])
    sizes, offs, ioctls = {}, {}, {}
    for line in out_file.read_text().splitlines():
        parts = line.split()
        if parts[0] == "size":
            sizes[parts[1]] = int(parts[2])
        elif parts[0] == "off":
            offs.setdefault(parts[1], []).append((parts[2], int(parts[3])))
        elif parts[0] == "ioctl":
            ioctls[parts[1]] = int(parts[2], 16)
    names = list(STRUCTS) + sorted(n for n in sizes if any(n.startswith(p) for p in STRUCT_PREFIXES))
    rs = [
        "// Generated by tools/uapi/gen_abi.py from tools/uapi/drm_layout.oibldofgate.out,",
        "// the output of tools/uapi/drm_layout.c and virtgpu_compat_layout.c built with gcc 14.3.0 on illumos",
        "// (oibldofgate, OpenIndiana Hipster 2026.04). Do not edit; rerun the generator.",
        "",
        "//! Compile-time checks of the uAPI layouts against gcc on illumos.",
        "",
        "use core::mem::{offset_of, size_of};",
        "",
        "use crate::*;",
        "",
    ]
    for n in names:
        if n not in sizes:
            raise SystemExit(f"{n} is not in the gcc output")
        rs.append(f"const _: () = assert!(size_of::<{n}>() == {sizes[n]});")
        for field, off in offs.get(n, []):
            rs.append(f"const _: () = assert!(offset_of!({n}, {field}) == {off});")
    rs.append("")
    for n in IOCTLS:
        rs.append(f"const _: () = assert!({n} == {ioctls[n]:#010x});")
    rs.append("")
    (root / "usr/src/uts/common/io/drm/drm-uapi/src/abi.rs").write_text("\n".join(rs))
    print(f"{len(names)} structures, {len(IOCTLS)} ioctl numbers")


if __name__ == "__main__":
    main()
