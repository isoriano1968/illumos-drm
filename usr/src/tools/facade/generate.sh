# Regenerates the Rust half of the DRM facade from its C headers
# (include/drm, the single source of truth):
#
#   usr/src/uts/common/io/drm/drm-facade-sys/src/bindings.rs  structures, constants and the
#                                           functions misc/drm_core exports (bindgen)
#   usr/src/uts/common/io/drm/drm_core/drm_core.mapfile                 the symbols misc/drm_core exports
#   usr/src/tools/facade/facade_layout.c            C half of the layout check
#   usr/src/tools/xtask/src/facade_table.rs               Rust half of the layout check
#                                           (gen_facade.py for the last three)
#
# Needs: bindgen (cargo install bindgen-cli, with a libclang), python3,
# rustfmt, and an illumos-gate checkout for the kernel headers:
#
#   ILLUMOS_GATE=~/illumos-gate usr/src/tools/facade/generate.sh
set -eu

ROOT=$(cd "$(dirname "$0")/../../../.." && pwd)
GATE=${ILLUMOS_GATE:?set ILLUMOS_GATE to an illumos-gate checkout}
BINDGEN=${BINDGEN:-bindgen}
OUT=$ROOT/usr/src/uts/common/io/drm/drm-facade-sys/src/bindings.rs

# clang's Solaris target predefines what a userland compile wants; a
# kernel compile (as the gate's) has none of it.
CFLAGS="--target=x86_64-pc-solaris2.11 -nostdinc -D_KERNEL \
    -U__EXTENSIONS__ -U_XOPEN_SOURCE -U_LARGEFILE64_SOURCE -U_LARGEFILE_SOURCE \
    -std=gnu99 -I$ROOT/usr/src/uts/common \
    -isystem $GATE/usr/src/uts/common -isystem $GATE/usr/src/uts/intel"

# Only what the facade headers declare is generated; the illumos kernel
# types they use come from usr/src/uts/common/io/drm/drm-facade-sys/src/kernel.rs (scalar
# typedefs, and opaque structures that are only passed by pointer).
# shellcheck disable=SC2086
"$BINDGEN" "$ROOT/usr/src/uts/common/drm/drm_facade.h" -o "$OUT" \
    --use-core --ctypes-prefix core::ffi \
    --allowlist-file '(.*/)?usr/src/uts/common/drm/.*\.h' --no-recursive-allowlist \
    --no-prepend-enum-name --default-enum-style consts \
    --with-derive-default --no-doc-comments \
    --raw-line "// Generated by tools/facade/generate.sh from include/drm (the facade headers)." \
    --raw-line "// Target: x86_64-pc-solaris2.11 kernel, headers from illumos-gate $(git -C "$GATE" rev-parse --short=10 HEAD)." \
    --raw-line "// Do not edit; rerun the generator." \
    --raw-line "" \
    --raw-line "pub use crate::kernel::*;" \
    -- $CFLAGS

python3 "$ROOT/usr/src/tools/facade/gen_facade.py" "$ROOT"
rustfmt --edition 2024 --config-path "$ROOT/rustfmt.toml" "$OUT" "$ROOT/usr/src/tools/xtask/src/facade_table.rs"
