"""Generates the derived files of the DRM facade from the bindgen output.

Input: crates/drm-facade-sys/src/bindings.rs (bindgen of include/drm).
Output:
  modules/drm_core/drm_core.mapfile         symbol scope of misc/drm_core (ld -B reduce):
                                  _init, _fini, _info and every facade
                                  function and variable global, the rest local
  include/drm/drm_facade.mapfile  the same symbols as EXTERN, for drivers
                                  linked with -z defs
  tools/facade/facade_layout.c    prints every facade structure's size and
                                  every named field's offset (gcc on illumos)
  xtask/src/facade_table.rs       the same lines from the Rust definitions
"""

import re
import sys

ROOT = sys.argv[1]
SRC = f"{ROOT}/usr/src/uts/common/io/drm/drm-facade-sys/src/bindings.rs"
text = open(SRC).read()

# Functions and variables of the extern blocks.
funcs = []
vars_ = []
for block in re.findall(r'unsafe extern "C" \{(.*?)\n\}', text, re.S):
    funcs += re.findall(r"pub fn (\w+)\(", block)
    vars_ += re.findall(r"pub static (?:mut )?(\w+):", block)
symbols = sorted(set(funcs + vars_))

MPL = """#
# This Source Code Form is subject to the terms of the Mozilla Public
# License, v. 2.0. If a copy of the MPL was not distributed with this
# file, You can obtain one at https://mozilla.org/MPL/2.0/.
#
"""

with open(f"{ROOT}/usr/src/uts/common/io/drm/drm_core/drm_core.mapfile", "w") as f:
    f.write(MPL)
    f.write("# Generated by tools/facade/gen_facade.py from the facade headers\n")
    f.write("# (include/drm); do not edit. misc/drm_core is linked with -B reduce and\n")
    f.write("# this mapfile: the module entry points and the facade stay global,\n")
    f.write("# every other symbol (the Rust core, compiler builtins) becomes local,\n")
    f.write("# so no driver can resolve against it.\n#\n")
    f.write("$mapfile_version 2\n\nSYMBOL_SCOPE {\n\tglobal:\n")
    for s in ["_init", "_fini", "_info"] + symbols:
        f.write(f"\t\t{s};\n")
    f.write("\tlocal:\n\t\t*;\n};\n")

with open(f"{ROOT}/usr/src/uts/common/drm/drm_facade.mapfile", "w") as f:
    f.write("#\n# SPDX-License-Identifier: MIT\n# Copyright 2026 The illumos-drm authors\n#\n")
    f.write("# Generated by tools/facade/gen_facade.py from the facade headers;\n")
    f.write("# do not edit. The symbols of misc/drm_core a driver may use: link with\n")
    f.write("#   ld -ztype=kmod -N misc/drm_core -z defs -M ddi.mapfile -M drm_facade.mapfile\n#\n")
    f.write("$mapfile_version 2\n\nSYMBOL_SCOPE {\n\tglobal:\n")
    for s in symbols:
        f.write(f"\t\t{s}\t{{ FLAGS = EXTERN }};\n")
    f.write("};\n")

# Structures with their named fields, from the generated definitions.
# Members of anonymous types are followed: a named member of an
# anonymous structure type (drm_device.managed) as "managed.lock" in both
# languages, an anonymous union or structure member (dma_fence's lock and
# list unions) by its members' names in C and through bindgen's
# __bindgen_anon_N in Rust. bindgen's own helper fields are left out.
types = {}
for m in re.finditer(r"#\[repr\(C[^\]]*\)\]\n(?:#\[derive[^\]]*\]\n)?pub (struct|union) (\w+) \{(.*?)\n\}", text, re.S):
    kind, name, body = m.groups()
    fields = [(n, t.rstrip(",")) for n, t in re.findall(r"^    (?:pub )?(\w+):[ ]?([^\n]*)$", body, re.M)]
    types[name] = (kind, fields)

def expand(fields, cpre="", rpre=""):
    out = []
    for fl, ty in fields:
        if fl == "bindgen_union_field" or fl.startswith("_bindgen"):
            continue
        anon = re.match(r"(?:__BindgenUnionField<)?(\w+__bindgen_ty_\d+)>?$", ty.strip())
        if fl.startswith("__bindgen_anon"):
            if anon and anon.group(1) in types:
                out += expand(types[anon.group(1)][1], cpre, f"{rpre}{fl}.")
            continue
        out.append((cpre + fl, rpre + fl))
        if anon and anon.group(1) in types:
            out += expand(types[anon.group(1)][1], f"{cpre}{fl}.", f"{rpre}{fl}.")
    return out

structs = []
for name, (kind, fields) in types.items():
    names = [x for x, _ in fields]
    if "_unused" in names or "_address" in names or "__bindgen" in name or name.startswith("_"):
        continue
    if kind == "union":
        continue
    structs.append((name, expand(fields)))

KERNEL = {"kmutex_t"}
structs = [(n, f) for (n, f) in structs if n not in KERNEL]

# C spelling: "struct x" for tagged structures, the typedef name otherwise.
import glob
hdrs = "".join(open(h).read() for h in glob.glob(f"{ROOT}/usr/src/uts/common/drm/*.h"))
def ctype(n):
    return f"struct {n}" if re.search(rf"\bstruct {n} \{{", hdrs) else n

c = []
c.append("""/*
 * SPDX-License-Identifier: MIT
 * Copyright 2026 The illumos-drm authors
 *
 * Generated by tools/facade/gen_facade.py; do not edit.
 *
 * The C half of the facade layout check: the size of every facade
 * structure and the offset of every named field as gcc lays them out for
 * the illumos kernel. Nothing runs: the values are emitted into the
 * assembly (the asm-offsets technique), so the kernel headers can be used
 * as a kernel compile uses them. On illumos:
 *
 *	gcc -m64 -D_KERNEL -std=gnu99 -I<illumos-drm>/include -S -o - \\
 *	    facade_layout.c | sed -n 's/^.*@@ //p' | tr -d '"' > out
 *	cargo xtask facade-check out
 */

#include <drm/drm_facade.h>

#define	SZ(n, t)	__asm__ volatile("\\n.ascii \\"@@ size " n " %c0\\"" \\
	: : "i" (sizeof (t)))
#define	OFF(n, t, f)	__asm__ volatile("\\n.ascii \\"@@ offset " n "." #f \\
	" %c0\\"" : : "i" (offsetof(t, f)))

void facade_layout(void);

void
facade_layout(void)
{""")
r = []
r.append("// Generated by tools/facade/gen_facade.py; do not edit.\n")
r.append("//! The Rust half of the facade layout check: the same lines as")
r.append("//! `tools/facade/facade_layout.c`, from drm-facade-sys.\n")
r.append("use core::mem::{offset_of, size_of};\n")
r.append("use drm_facade_sys as f;\n")
r.append("/// Every structure size and named field offset, one line each.")
r.append("pub fn lines() -> Vec<String> {")
r.append("    vec![")
KEYWORDS = ("type", "as", "ref", "mod", "fn", "priv", "box", "move", "match", "loop", "self", "use", "where", "impl", "dyn", "final", "override", "virtual", "abstract", "become", "do", "macro", "typeof", "unsized", "yield", "try", "async", "await", "gen")
nsz = noff = 0
for name, fields in structs:
    c.append(f'\tSZ("{name}", {ctype(name)});')
    r.append(f'        format!("size {name} {{}}", size_of::<f::{name}>()),')
    nsz += 1
    for cf, fl in fields:
        cf = ".".join(x[:-1] if x.endswith("_") and x[:-1] in KEYWORDS else x for x in cf.split("."))
        c.append(f'\tOFF("{name}", {ctype(name)}, {cf});')
        r.append(f'        format!("offset {name}.{cf} {{}}", offset_of!(f::{name}, {fl})),')
        noff += 1
c.append("}")
r.append("    ]")
r.append("}")
open(f"{ROOT}/usr/src/tools/facade/facade_layout.c", "w").write("\n".join(c) + "\n")
open(f"{ROOT}/usr/src/tools/xtask/src/facade_table.rs", "w").write("\n".join(r) + "\n")
print(f"facade: {len(funcs)} functions, {len(vars_)} variables, {nsz} structures, {noff} offsets")
