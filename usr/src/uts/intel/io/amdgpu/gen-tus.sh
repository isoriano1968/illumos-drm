# Writes tus.txt: the TUs of amdgpu.ko for the illumos configuration
# (gen-tus.mk), minus the TUs of EXCLUDED (each with its reason), plus the
# TTM, GPU scheduler and DRM helper TUs amdgpu needs (CARRIED), which move
# to their own misc modules once they build, then the illumos glue
# (illumos/*.c of this directory). Linux TUs are paths relative to
# usr/src/contrib/linux.
#
# A maintainer tool, like i915n's config/gen-config.py: Linux's amdgpu
# Kbuild Makefiles are not vendored, so it reads them from a full upstream
# checkout at the pinned commit (usr/src/uts/intel/io/i915n/PIN). Run it
# when the pin or the configuration changes and commit the output.
#
#   usr/src/uts/intel/io/amdgpu/gen-tus.sh <full linux checkout> > usr/src/uts/intel/io/amdgpu/tus.txt
set -euo pipefail
PATH=/usr/gnu/bin:$PATH
export LC_ALL=C
HERE=$(cd "$(dirname "$0")" && pwd)
LINUX=${1:?usage: gen-tus.sh <full linux checkout>}
MAKE=${MAKE:-gmake}
AMD=drivers/gpu/drm/amd/amdgpu

# TU and reason (amdgpu.ko's relative to $AMD, the others to the tree)
EXCLUDED="
amdgpu_vkms.c	GPL-2.0: MIT stub in illumos/amdgpu_vkms_stub.c
amdgpu_dma_buf.c	amdgpu's own dma_buf_ops: PRIME is the DRM core's, illumos/amdgpu_dma_buf_illumos.c
amdgpu_trace_points.c	tracepoints: lkpi has none (no-op trace headers)
drivers/gpu/drm/ttm/ttm_bo_vm.c	Linux VM faults (vm_fault, vmf_insert_pfn): replaced by an illumos devmap path (to do)
drivers/gpu/drm/ttm/ttm_backup.c	shmem swap-out of BOs: illumos/ttm_backup_illumos.c (none yet)
../display/dmub/src/dmub_dcn401.c	DCN 4.01 (RDNA 4): dcn_4_1_0_sh_mask.h has no licence statement; dmub_srv.c reports the ASIC unsupported on illumos
../display/dc/irq/dcn401/irq_service_dcn401.c	DCN 4.01: the same header; only DCN 4.01's resource pool (DC_FP, not built) calls it
../display/dc/gpio/dcn401/hw_factory_dcn401.c	DCN 4.01: the same header; hw_factory.c refuses DCN 4.01 on illumos
../display/dc/gpio/dcn401/hw_translate_dcn401.c	DCN 4.01: the same header; hw_translate.c refuses DCN 4.01 on illumos

"
CARRIED="
drivers/gpu/drm/ttm/ttm_tt.c
drivers/gpu/drm/ttm/ttm_bo.c
drivers/gpu/drm/ttm/ttm_bo_util.c
drivers/gpu/drm/ttm/ttm_module.c
drivers/gpu/drm/ttm/ttm_execbuf_util.c
drivers/gpu/drm/ttm/ttm_range_manager.c
drivers/gpu/drm/ttm/ttm_resource.c
drivers/gpu/drm/ttm/ttm_pool.c
drivers/gpu/drm/ttm/ttm_device.c
drivers/gpu/drm/ttm/ttm_sys_manager.c
drivers/gpu/drm/scheduler/sched_main.c
drivers/gpu/drm/scheduler/sched_fence.c
drivers/gpu/drm/scheduler/sched_entity.c
drivers/gpu/drm/scheduler/sched_rq.c
drivers/gpu/drm/drm_exec.c
drivers/gpu/buddy.c
drivers/gpu/drm/drm_buddy.c
drivers/gpu/drm/drm_suballoc.c
"
echo "# Generated by usr/src/uts/intel/io/amdgpu/gen-tus.sh from Linux $(git -C "$LINUX" describe --tags 2>/dev/null || echo '?'); do not edit."
echo "# amdgpu.ko's TUs, then the carried TUs (paths relative to"
echo "# usr/src/contrib/linux), then illumos/*.c (this directory)."
echo "$EXCLUDED" | grep . | sed 's/^\([^\t]*\)\t\(.*\)/# excluded: \1 (\2)/'
"$MAKE" -s -f "$HERE/gen-tus.mk" LINUX="$LINUX" print | tr ' ' '\n' | grep . |
    sed 's/\.o$/.c/' | grep -vxF -f <(echo "$EXCLUDED" | grep . | cut -f1) |
    while read -r t; do
	[ -f "$LINUX/$AMD/$t" ] ||
	    { echo "gen-tus.sh: $t not in the tree" >&2; exit 1; }
	# ../pm/x.c and ../display/x.c: tree-relative, normalized
	echo "$AMD/$t" | sed -e ':a' -e 's|/[^/.][^/]*/\.\./|/|' -e 'ta'
    done
echo "$CARRIED" | grep . | grep -vxF -f <(echo "$EXCLUDED" | grep . | cut -f1)
(cd "$HERE" && ls illumos/*.c | sort)
