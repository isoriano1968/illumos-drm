"""Writes drivers/i915/config.h: the CONFIG_* values the i915 sources and
misc/drm_kms' carried sources test (both are built with it).

Usage: gen-config.py <patched linux tree> > config.h

The values come from linux-v7.2-r5c.config (the Linux configuration of the
R5c measurement build, made by drivers/i915/config/make-config.sh from the
R5 analysis configuration), restricted to the options that i915's sources,
Intel's shared headers, the DRM headers and the TUs of
carried/drm_kms/tus.txt mention, with the OVERRIDES below for what the
illumos build leaves out although Linux's Kconfig keeps it.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
# Linux keeps these on for x86 or by default; the LinuxKPI layer provides
# the "off" variant (see linuxkpi/include/lkpi/config.h).
OVERRIDES = {
    "CONFIG_PERF_EVENTS": None,      # no perf PMU (i915_pmu.c not built)
    "CONFIG_TRACEPOINTS": None,
    "CONFIG_FTRACE": None,
    "CONFIG_DEBUG_FS": None,
    "CONFIG_PM": None,
    "CONFIG_PM_SLEEP": None,
    "CONFIG_ACPI": None,
    "CONFIG_MMU_NOTIFIER": None,
    "CONFIG_COMPAT": None,
    "CONFIG_HWMON": None,
    "CONFIG_INTEL_IOMMU": None,
    "CONFIG_IOMMU_API": None,
    "CONFIG_DRM_I915_GVT": None,
    "CONFIG_DRM_I915_PXP": None,
    "CONFIG_DRM_I915_CAPTURE_ERROR": None,
    "CONFIG_DRM_I915_USERPTR": None,
    "CONFIG_DRM_FBDEV_EMULATION": None,
    "CONFIG_SND_HDA_I915": None,
    "CONFIG_PROC_FS": None,
    "CONFIG_SYSFS": None,
    "CONFIG_SWAP": None,
    "CONFIG_PREEMPT_COUNT": None,
    "CONFIG_DEBUG_LOCK_ALLOC": None,
    "CONFIG_LOCKDEP": None,
    "CONFIG_PROVE_LOCKING": None,
    "CONFIG_KASAN": None,
    "CONFIG_PARAVIRT": None,
    "CONFIG_XEN": None,
    "CONFIG_X86_32": None,
    # i915n display (design note i915n-kms-design.md section 3): no
    # backlight class device, no AGP, no device-private memory, no sysrq,
    # no panel bridges.
    "CONFIG_BACKLIGHT_CLASS_DEVICE": None,
    "CONFIG_AGP": None,
    "CONFIG_ZONE_DEVICE": None,
    "CONFIG_MAGIC_SYSRQ": None,
    "CONFIG_WERROR": None,
    "CONFIG_DRM_PANEL_BRIDGE": None,
}


def main():
    tree = sys.argv[1]
    cfg = {}
    for line in open(os.path.join(HERE, "linux-v7.2-r5c.config")):
        m = re.match(r"^(CONFIG_[A-Z0-9_]+)=(.*)$", line.strip())
        if m:
            cfg[m.group(1)] = m.group(2)
    used = set()
    for d in ("drivers/gpu/drm/i915", "include/drm/intel", "include/uapi/drm",
              "include/drm/display"):
        for root, _dirs, files in os.walk(os.path.join(tree, d)):
            if "/gvt" in root or "/selftests" in root:
                continue
            for f in files:
                if f.endswith((".c", ".h")):
                    text = open(os.path.join(root, f), errors="replace").read()
                    used.update(re.findall(r"\bCONFIG_[A-Z0-9_]+", text))
    # The DRM headers (not their subdirectories but display/ and intel/)
    # and misc/drm_kms' Linux TUs.
    drm = os.path.join(tree, "include/drm")
    files = [os.path.join(drm, f) for f in os.listdir(drm) if f.endswith(".h")]
    files.append(os.path.join(tree, "include/linux/hdmi.h"))
    for line in open(os.path.join(HERE, "../../../../common/io/drm_kms/tus.txt")):
        line = line.strip()
        if line and not line.startswith("#"):
            files.append(os.path.join(tree, line))
    for f in files:
        text = open(f, errors="replace").read()
        used.update(re.findall(r"\bCONFIG_[A-Z0-9_]+", text))
    used.update(("CONFIG_X86", "CONFIG_X86_64", "CONFIG_64BIT", "CONFIG_PCI",
                 "CONFIG_MMU", "CONFIG_SMP", "CONFIG_DRM_I915"))
    out = ["/*", " * SPDX-License-Identifier: MIT", " * Copyright 2026 The illumos-drm authors", " *",
           " * Generated by drivers/i915/config/gen-config.py; do not edit.",
           " * The CONFIG_* options i915 and misc/drm_kms test, for the illumos build.", " */",
           "#ifndef _I915_ILLUMOS_CONFIG_H", "#define\t_I915_ILLUMOS_CONFIG_H", ""]
    for name in sorted(used):
        base = name[:-7] if name.endswith("_MODULE") else name
        if base in OVERRIDES or name in OVERRIDES:
            continue
        v = cfg.get(base)
        if v is None:
            continue
        if v == "y":
            if name == base:
                out.append(f"#define\t{name}\t1")
        elif v == "m":
            if name.endswith("_MODULE"):
                out.append(f"#define\t{name}\t1")
        else:
            if name == base:
                out.append(f"#define\t{name}\t{v}")
    out += ["", "#endif", ""]
    sys.stdout.write("\n".join(out))


main()
