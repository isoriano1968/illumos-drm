# Writes the illumos replacement of one of i915's tracepoint headers
# (i915_trace.h, intel_uncore_trace.h; GPL-2.0 in Linux): an MIT header
# that keeps the original's include guard and its includes of other
# (MIT) headers, and defines every trace_<event>() and
# trace_<event>_enabled() the original declares as a no-op macro. The
# illumos build has no tracepoints (lkpi/config.h refuses
# CONFIG_TRACEPOINTS), so the replacement only carries event names; no
# text of the original is copied. fetch-and-patch.sh runs this on the
# pinned tree's original (git show HEAD:<path>) and writes the result over
# the working file, so the GPL header never reaches a compile.
#
#   gen-trace-stubs.py <original header> <output>
import re
import sys

src, out = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8").read()

names = set()
for m in re.finditer(r"^\s*(TRACE_EVENT|TRACE_EVENT_CONDITION|TRACE_EVENT_FN)\(\s*(\w+)\s*,",
                     text, re.M):
    names.add(m.group(2))
for m in re.finditer(r"^\s*(DEFINE_EVENT|DEFINE_EVENT_PRINT|DEFINE_EVENT_CONDITION)\(\s*\w+\s*,\s*(\w+)\s*,",
                     text, re.M):
    names.add(m.group(2))
for m in re.finditer(r"^\s*(?:static\s+inline\s+void\s+)?\btrace_(\w+)\s*\(", text, re.M):
    names.add(m.group(1))
names.discard("")

guard = None
m = re.search(r"^#if\s+!defined\((\w+)\)", text, re.M) or \
    re.search(r"^#ifndef\s+(\w+)\s*$", text, re.M)
if m:
    guard = m.group(1)
includes = ["<linux/types.h>"]
for m in re.finditer(r'^#include\s+([<"][^>"]+[>"])', text, re.M):
    inc = m.group(1)
    if "tracepoint.h" in inc or "define_trace.h" in inc:
        continue
    if inc not in includes:
        includes.append(inc)

if not names:
    sys.exit(f"gen-trace-stubs: no events found in {src}")

with open(out, "w", encoding="utf-8") as f:
    f.write("/* SPDX-License-Identifier: MIT */\n")
    f.write("/*\n * Generated by illumos-drm drivers/i915/illumos/gen-trace-stubs.py:\n")
    f.write(" * the no-op tracepoints of the illumos build (no tracepoints) in place\n")
    f.write(" * of Linux's header of the same name. Only event names are taken from it.\n */\n")
    if guard:
        f.write(f"#ifndef {guard}\n#define\t{guard}\n\n")
    for inc in includes:
        f.write(f"#include {inc}\n")
    f.write("\n")
    for n in sorted(names):
        f.write(f"#define\ttrace_{n}(...)\tdo {{ }} while (0)\n")
        f.write(f"#define\ttrace_{n}_enabled()\t(false)\n")
    if guard:
        f.write(f"\n#endif /* {guard} */\n")
print(f"gen-trace-stubs: {out}: {len(names)} events")
