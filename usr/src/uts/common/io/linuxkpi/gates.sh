set -eu
HERE=$(CDPATH= cd "$(dirname "$0")" && pwd)
phase=$1 OUT=$2
case $phase in
private)
	{
		echo '# Generated by linuxkpi/build.sh from linuxkpi/private.d/*.txt.'
		echo '$mapfile_version 2'
		echo 'SYMBOL_SCOPE {'
		echo '	global:'
		cat "$HERE"/private.d/*.txt | sed 's/#.*//' | awk 'NF { print $1 }' |
		    sort -u | sed 's/^/		/; s/$/	{ FLAGS = EXTERN };/'
		echo '};'
	} > "$OUT/private.mapfile"
;;
exports)
	{
		echo '#'
		echo '# SPDX-License-Identifier: MIT'
		echo '# Generated by linuxkpi/build.sh: the symbols of misc/linuxkpi a driver'
		echo '# may use. Link with -N misc/linuxkpi -z defs -M linuxkpi.mapfile.'
		echo '#'
		echo '$mapfile_version 2'
		echo ''
		echo 'SYMBOL_SCOPE {'
		echo '	global:'
		/usr/bin/nm -g "$OUT/linuxkpi" | awk -F'|' '$5 ~ /GLOB/ && $7 !~ /UNDEF/ {gsub(/ /,"",$8); print $8}' |
		    grep -v -x -e _init -e _fini -e _info | sort -u | sed 's/^/		/; s/$/	{ FLAGS = EXTERN };/'
		echo '};'
	} > "$OUT/linuxkpi.mapfile"
;;
*) exit 2 ;;
esac
